from sqlalchemy.ext.asyncio import create_async_engine, AsyncSession
from sqlalchemy.orm import sessionmaker
import pathlib
from contextlib import asynccontextmanager
from .models import Base
import config
from config.db_config import sqlite_db_config

# Keep a cache of engines
_engines = {}


async def create_database_if_not_exists(db_type: str):
    """dyer 裁剪版：只支持 SQLite，数据库文件由 SQLAlchemy 自动创建。"""
    if db_type not in ("sqlite", "db"):
        raise ValueError(f"dyer 引擎仅支持 sqlite 存储，收到: {db_type}")
    pathlib.Path(sqlite_db_config["db_path"]).parent.mkdir(parents=True, exist_ok=True)


def get_async_engine(db_type: str = None):
    if db_type is None:
        db_type = config.SAVE_DATA_OPTION

    if db_type in _engines:
        return _engines[db_type]

    if db_type in ["json", "jsonl", "csv", "excel"]:
        return None

    if db_type in ("sqlite", "db"):
        db_url = f"sqlite+aiosqlite:///{sqlite_db_config['db_path']}"
    else:
        raise ValueError(f"Unsupported database type: {db_type}")

    engine = create_async_engine(db_url, echo=False)
    _engines[db_type] = engine
    return engine


async def create_tables(db_type: str = None):
    if db_type is None:
        db_type = config.SAVE_DATA_OPTION
    await create_database_if_not_exists(db_type)
    engine = get_async_engine(db_type)
    if engine:
        async with engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)


@asynccontextmanager
async def get_session() -> AsyncSession:
    engine = get_async_engine(config.SAVE_DATA_OPTION)
    if not engine:
        yield None
        return
    AsyncSessionFactory = sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
    session = AsyncSessionFactory()
    try:
        yield session
        await session.commit()
    except Exception as e:
        await session.rollback()
        raise e
    finally:
        await session.close()
